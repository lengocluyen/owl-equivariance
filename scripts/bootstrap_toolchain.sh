#!/usr/bin/env bash
# Fetch a JDK and Maven into a local directory. Nothing is installed system-wide.
#
# Writes .owleq-toolchain.env at the repo root; source it to put the toolchain on PATH:
#
#   bash scripts/bootstrap_toolchain.sh
#   source .owleq-toolchain.env
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TOOLS="${OWLEQ_TOOLS_DIR:-$REPO_ROOT/.tools}"
JDK_VERSION="${OWLEQ_JDK_VERSION:-25}"
MAVEN_VERSION="${OWLEQ_MAVEN_VERSION:-3.9.9}"

mkdir -p "$TOOLS"

case "$(uname -s)" in
  Linux*)   OS=linux  ;;
  Darwin*)  OS=mac    ;;
  MINGW*|MSYS*|CYGWIN*) OS=windows ;;
  *) echo "unsupported platform: $(uname -s)" >&2; exit 1 ;;
esac
case "$(uname -m)" in
  x86_64|amd64) ARCH=x64   ;;
  arm64|aarch64) ARCH=aarch64 ;;
  *) echo "unsupported architecture: $(uname -m)" >&2; exit 1 ;;
esac

# ---------------------------------------------------------------- JDK
JDK_DIR="$(find "$TOOLS" -maxdepth 1 -type d -name "jdk-${JDK_VERSION}*" 2>/dev/null | head -1)"
if [[ -z "$JDK_DIR" ]]; then
  echo "fetching Temurin JDK ${JDK_VERSION} (${OS}/${ARCH})..."
  URL="https://api.adoptium.net/v3/binary/latest/${JDK_VERSION}/ga/${OS}/${ARCH}/jdk/hotspot/normal/eclipse"
  if [[ "$OS" == "windows" ]]; then
    curl -fsSL --retry 3 -o "$TOOLS/jdk.zip" "$URL"
    (cd "$TOOLS" && unzip -q -o jdk.zip && rm -f jdk.zip)
  else
    curl -fsSL --retry 3 -o "$TOOLS/jdk.tar.gz" "$URL"
    (cd "$TOOLS" && tar -xzf jdk.tar.gz && rm -f jdk.tar.gz)
  fi
  JDK_DIR="$(find "$TOOLS" -maxdepth 1 -type d -name "jdk-${JDK_VERSION}*" | head -1)"
fi
# macOS archives nest the JDK inside Contents/Home.
if [[ -d "$JDK_DIR/Contents/Home" ]]; then
  JDK_DIR="$JDK_DIR/Contents/Home"
fi

# ---------------------------------------------------------------- Maven
MVN_DIR="$TOOLS/apache-maven-$MAVEN_VERSION"
if [[ ! -d "$MVN_DIR" ]]; then
  echo "fetching Apache Maven $MAVEN_VERSION..."
  curl -fsSL --retry 3 -o "$TOOLS/maven.zip" \
    "https://archive.apache.org/dist/maven/maven-3/${MAVEN_VERSION}/binaries/apache-maven-${MAVEN_VERSION}-bin.zip"
  if command -v unzip >/dev/null 2>&1; then
    (cd "$TOOLS" && unzip -q -o maven.zip && rm -f maven.zip)
  elif command -v python3 >/dev/null 2>&1; then
    (cd "$TOOLS" && python3 -m zipfile -e maven.zip . && rm -f maven.zip)
  else
    echo "cannot extract Maven: install unzip or Python 3" >&2
    exit 1
  fi
fi

MVN_BIN="$MVN_DIR/bin/mvn"
[[ "$OS" == "windows" ]] && MVN_BIN="$MVN_DIR/bin/mvn.cmd"

cat > "$REPO_ROOT/.owleq-toolchain.env" <<EOF
# Generated by scripts/bootstrap_toolchain.sh -- source this file.
export OWLEQ_JAVA_HOME="$JDK_DIR"
export OWLEQ_MVN="$MVN_BIN"
export OWLEQ_M2="$TOOLS/m2"
export JAVA_HOME="\$OWLEQ_JAVA_HOME"
export PATH="\$JAVA_HOME/bin:$MVN_DIR/bin:\$PATH"
EOF

"$JDK_DIR/bin/java" -version 2>&1 | head -1
echo "toolchain ready under $TOOLS"
echo "run:  source .owleq-toolchain.env"
